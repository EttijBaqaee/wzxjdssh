 function t(value,params){
  if(typeof value!=='string')return value;
  const translated=language==='en'?english[value.trim()]:undefined;
  let result=translated===undefined?value:value.slice(0,value.length-value.trimStart().length)+translated+value.slice(value.trimEnd().length);
  if(params)result=result.replace(/\{([a-z]+)\}/gi,(match,key)=>Object.prototype.hasOwnProperty.call(params,key)?String(params[key]):match);
  return result;
 }
